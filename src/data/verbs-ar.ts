export function conjugateAR(inf: string): string[] | null {
  const v = VERBS_AR.find((x) => x.inf === inf);
  if (!v) return null;
  const base = v.y.slice(1); // retira o prefixo ي mantendo as harakat
  return ["أ" + base, "ت" + base, v.y, "ن" + base, "ت" + v.pl.slice(1), v.pl];
}

export function withPronounAR(person: number, form: string): string {
  return `${AR_PRONOUNS[person]} ${form}`;
}
